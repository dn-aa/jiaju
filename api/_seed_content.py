def seed():
    db = SessionLocal()
    try:
        # 为 jobs 增加 cover_image 列（幂等）
        try:
            db.execute(__import__("sqlalchemy").text(
                "ALTER TABLE jobs ADD COLUMN cover_image VARCHAR(512) NULL"))
            db.commit()
            print("[seed] jobs 增加 cover_image 列")
        except Exception:
            db.rollback()

        # 产品
        if db.query(Product).count() < 12:
            for i, (name, series, cat, code, desc) in enumerate(PRODUCTS):
                db.add(Product(
                    category_id=cat, series=series, product_code=code, name=name,
                    description=f"<p>{desc}</p><ul><li>环保板材，符合国家ENF级标准</li><li>原创设计，支持尺寸定制</li><li>五年质保，全国上门安装</li></ul>",
                    spec_params={"材质": "实木/岩板/科技布", "风格": series, "保修": "5年", "定制": "支持"},
                    cover_image=cyc(PROD_IMG, i), gallery=[cyc(PROD_IMG, i), cyc(PROD_IMG, i+5)],
                    status="on", is_top=1 if i < 3 else 0, sort=i,
                ))
            db.commit()
            print(f"[seed] 产品 +{len(PRODUCTS)}")

        # 案例
        if db.query(Case).count() < 9:
            for i, (title, ctype, style, space, area, desc) in enumerate(CASES):
                db.add(Case(
                    title=title, type=ctype, style=style, space=space, area=area,
                    cover=cyc(CASE_IMG, i), gallery=[cyc(CASE_IMG, i), cyc(CASE_IMG, i+6)],
                    background=f"<p>项目位于{space}，面积{area}，业主期望在空间里安放从容的日常。</p>",
                    description=f"<p>{desc}</p><p>设计亮点：定制柜体与成品家具协同，统一材质语言，兼顾收纳与美学。</p>",
                    sort=i,
                ))
            db.commit()
            print(f"[seed] 案例 +{len(CASES)}")

        # 新闻
        if db.query(Article).count() < 9:
            for i, (title, cat, summary) in enumerate(ARTICLES):
                db.add(Article(
                    title=title, category=cat, summary=summary, cover_image=cyc(NEWS_IMG, i),
                    body=f"<p>{summary}</p><p>蓝鸟家居将持续以原创设计与智能制造，为更多中国家庭提供一体化的全屋解决方案。</p>",
                    source="蓝鸟家居" if cat == "company" else "行业观察", author="蓝鸟内容组",
                    publish_at=datetime.strptime(PUB_DATES[i], "%Y-%m-%d"),
                    is_published=1, is_top=1 if i < 2 else 0,
                ))
            db.commit()
            print(f"[seed] 新闻 +{len(ARTICLES)}")

        # 职位
        if db.query(Job).count() < 9:
            for i, (title, jtype, dept, loc, salary, resp, req) in enumerate(JOBS):
                db.add(Job(
                    title=title, type=jtype, dept=dept, location=loc, salary=salary,
                    cover_image=cyc(JOB_IMG, i),
                    responsibility=f"<p>{resp}</p>",
                    requirement=f"<p>{req}</p><p>我们提供：五险一金、带薪年假、定期培训、清晰的晋升通道与有温度的团队氛围。</p>",
                    sort=i,
                ))
            db.commit()
            print(f"[seed] 职位 +{len(JOBS)}")

        print("[seed] 完成 ✅")
        print("  产品:", db.query(Product).count(),
              " 案例:", db.query(Case).count(),
              " 新闻:", db.query(Article).count(),
              " 职位:", db.query(Job).count())
    finally:
        db.close()


if __name__ == "__main__":
    seed()
